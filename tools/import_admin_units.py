"""Builds infra/seed/admin_units.json for all of Uganda (docs/PLAN.md §3).

Source: OCHA Common Operational Dataset, "Uganda - Subnational Administrative
Boundaries" (UBOS, valid 2020-08-24), table edition, CC BY-IGO:
https://data.humdata.org/dataset/cod-ab-uga

    uv run --no-project --with openpyxl python -I tools/import_admin_units.py uga_admin_boundaries.xlsx

Levels kept: country -> region (4) -> district (135) -> sub-county (1,520).
Counties are skipped: they do not take part in water governance, so a
sub-county's parent is its district. Parishes and villages are added per
district as districts join (the dataset has none). IDs follow the existing
seed (uuid5 of "admin:" + code), so the pilot units keep theirs.
"""

from __future__ import annotations

import json
import re
import sys
import unicodedata
import uuid
from pathlib import Path

import openpyxl

NS = uuid.UUID("6f1c9f3e-2b1a-4c55-9a51-0d7f6b0a9c01")
OUT = Path(__file__).resolve().parents[1] / "infra" / "seed" / "admin_units.json"

# The pilot village and its placeholder parents (test data and the perf
# fixture use them); to verify with Abim District.
PILOT = [
    ("UG-ABIM-SC1", "subcounty", "TODO-verify sub-county", "UG-ABIM"),
    ("UG-ABIM-SC1-P1", "parish", "TODO-verify parish", "UG-ABIM-SC1"),
    ("ABIM-ENT", "village", "Entebbe", "UG-ABIM-SC1-P1"),
]


def uid(code: str) -> str:
    return str(uuid.uuid5(NS, "admin:" + code))


def slug(name: str) -> str:
    plain = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return re.sub(r"[^A-Z0-9]+", "-", plain.upper()).strip("-")


def rows(wb: openpyxl.Workbook, sheet: str) -> list[dict[str, object]]:
    data = list(wb[sheet].iter_rows(values_only=True))
    head = data[0]
    return [dict(zip(head, r, strict=False)) for r in data[1:]]


def unit(code, level, name, parent, pcode=None, lat=None, lon=None) -> dict[str, object]:
    return {
        "id": uid(code),
        "code": code,
        "level": level,
        "name": name,
        "parent_id": uid(parent) if parent else None,
        "pcode": pcode,
        "center_lat": round(lat, 5) if lat is not None else None,
        "center_lon": round(lon, 5) if lon is not None else None,
    }


def main() -> None:
    wb = openpyxl.load_workbook(sys.argv[1], read_only=True)
    country = rows(wb, "uga_admin0")[0]
    units = [
        unit("UG", "country", "Uganda", None, "UG", country["center_lat"], country["center_lon"])
    ]
    region_code: dict[object, str] = {}
    for r in sorted(rows(wb, "uga_admin1"), key=lambda r: str(r["adm1_name"])):
        code = f"UG-R-{slug(str(r['adm1_name']))}"
        region_code[r["adm1_pcode"]] = code
        units.append(
            unit(code, "region", f"{r['adm1_name']} Region", "UG", str(r["adm1_pcode"]),
                 r["center_lat"], r["center_lon"])  # fmt: skip
        )
    district_code: dict[object, str] = {}
    for r in sorted(rows(wb, "uga_admin2"), key=lambda r: str(r["adm2_name"])):
        code = f"UG-{slug(str(r['adm2_name']))}"
        district_code[r["adm2_pcode"]] = code
        units.append(
            unit(code, "district", str(r["adm2_name"]), region_code[r["adm1_pcode"]],
                 str(r["adm2_pcode"]), r["center_lat"], r["center_lon"])  # fmt: skip
        )
    for r in sorted(rows(wb, "uga_admin4"), key=lambda r: (str(r["adm2_name"]), str(r["adm4_name"]))):
        parent = district_code[r["adm2_pcode"]]
        units.append(
            unit(f"{parent}-{slug(str(r['adm4_name']))}", "subcounty", str(r["adm4_name"]),
                 parent, str(r["adm4_pcode"]), r["center_lat"], r["center_lon"])  # fmt: skip
        )
    units += [unit(code, level, name, parent) for code, level, name, parent in PILOT]
    codes = [u["code"] for u in units]
    assert len(codes) == len(set(codes)), "duplicate codes"
    OUT.write_text(
        json.dumps(
            {
                "schema": "watercheck.admin_units/2",
                "version": 2,
                "source": (
                    "Regions, districts and sub-counties: OCHA COD-AB Uganda (UBOS, valid "
                    "2020-08-24), CC BY-IGO, https://data.humdata.org/dataset/cod-ab-uga. "
                    "Generated by tools/import_admin_units.py."
                ),
                "notes": (
                    "Parishes and villages are added per district as districts join. The "
                    "UG-ABIM-SC1 sub-county and its parish are pilot placeholders to verify "
                    "with Abim District."
                ),
                "admin_units": units,
            },
            ensure_ascii=False,
            indent=1,
        )
        + "\n",
        encoding="utf-8",
    )
    levels: dict[str, int] = {}
    for u in units:
        levels[str(u["level"])] = levels.get(str(u["level"]), 0) + 1
    print(f"wrote {OUT} ({OUT.stat().st_size / 1e3:.0f} KB): {levels}")


if __name__ == "__main__":
    main()
